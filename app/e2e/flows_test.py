from playwright.sync_api import sync_playwright
import re, sys
import os
B=os.environ.get('BASE_URL', 'http://localhost:4173/')
SHOT=os.environ.get('SHOT_DIR', './e2e/screens/')
results=[]
def ok(name, cond, extra=''):
    results.append((('PASS' if cond else 'FAIL'), name, extra))
def noscroll(pg, label):
    sw=pg.evaluate('document.documentElement.scrollWidth'); ok(f'no horizontal scroll @360 · {label}', sw<=360, f'scrollWidth={sw}')
with sync_playwright() as p:
    br=p.chromium.launch()
    ctx=br.new_context(viewport={'width':360,'height':780}, color_scheme='light')
    pg=ctx.new_page(); errs=[]
    pg.on('pageerror', lambda e: errs.append(str(e))); pg.on('console', lambda m: m.type=='error' and 'ERR_TUNNEL' not in m.text and errs.append(m.text))
    pg.goto(B); pg.wait_for_selector('#step-title')
    ok('title on load', pg.title().startswith('Step 1 of 7'), pg.title()); noscroll(pg,'A simulator')
    pg.screenshot(path=SHOT+'app-A.png', full_page=True)
    pg.get_by_role('button', name='Increase amount by $100').click()
    pg.get_by_role('radio', name='12 weeks').click()
    t=pg.locator('.quote-card').inner_text()
    ok('simulator recalculates ($2,100 × 1.25 = $2,625)', '$2,625' in t and '$2,100' in t, t.replace('\n',' | ')[:120])
    pg.get_by_role('button', name='Decrease amount by $100').click()
    ok('uneven payments: last payment shown ($2,500 / 12)', 'Last payment' in pg.locator('.quote-card').inner_text())
    amt=pg.locator('.amount-input'); amt.fill('99999'); amt.press('Tab')
    ok('amount clamps to $10,000 with a note', pg.locator('.amount-input').input_value()=='$10,000' and 'largest' in pg.content())
    pg.get_by_role('button', name='what that means').click()
    ok('"not a loan" sheet opens', pg.get_by_role('dialog').is_visible())
    pg.keyboard.press('Escape'); ok('sheet closes with Escape', pg.get_by_role('dialog').count()==0)
    pg.get_by_role('button', name='Check if I can apply').click(); pg.wait_for_selector('text=Three quick')
    ok('B: continue disabled until answered', pg.get_by_role('button', name='Continue').is_disabled())
    st=pg.get_by_role('combobox'); st.fill('cal'); 
    ok('state combobox filters as you type', pg.get_by_role('option').count()==1 and 'California' in pg.get_by_role('listbox').inner_text())
    st.press('Enter'); pg.get_by_role('radio', name='3+ years').click(); pg.get_by_role('radio', name='Over $6,000').click()
    noscroll(pg,'B eligibility'); pg.screenshot(path=SHOT+'app-B.png', full_page=True)
    pg.get_by_role('button', name='Continue').click()
    ok('D1: unserved state is told before any personal data', 'isn’t available in California' in pg.locator('h1').inner_text())
    noscroll(pg,'D1'); pg.screenshot(path=SHOT+'app-D1.png', full_page=True)
    pg.get_by_role('button', name='I picked the wrong state').click()
    st=pg.get_by_role('combobox'); st.click(); st.fill('zz'); pg.wait_for_timeout(300)
    ok('combobox empty state message', 'No state matches' in ' '.join(pg.locator('[role=status]').all_inner_texts()))
    st.fill('Flo'); st.press('ArrowDown'); st.press('Enter')
    pg.get_by_role('radio', name='Less than 3 months').click(); pg.get_by_role('button', name='Continue').click()
    ok('D2: below minimums explains why', 'Not yet' in pg.locator('h1').inner_text())
    pg.get_by_role('button', name='I picked the wrong answer').click()
    pg.get_by_role('radio', name='1–3 years').click(); pg.get_by_role('button', name='Continue').click()
    pg.wait_for_selector('text=you can apply')
    noscroll(pg,'C'); pg.screenshot(path=SHOT+'app-C.png', full_page=True)
    pg.get_by_role('button', name='Save my quote and continue').click(); pg.wait_for_timeout(200)
    print('DBG2', pg.evaluate('document.activeElement.outerHTML')[:160])
    ok('C: empty email error + focus', 'Enter your email' in pg.content() and pg.evaluate('document.activeElement.getAttribute("aria-invalid")')=='true')
    pg.get_by_label(re.compile('Where should we send')).fill('name@example.com')
    pg.get_by_role('button', name='Save my quote and continue').click()
    pg.wait_for_selector('text=A bit')
    ok('3: quote-saved banner with email', 'We sent it to name@example.com' in pg.content())
    ok('focus moves to new heading', pg.evaluate('document.activeElement.id')=='step-title')
    pg.get_by_role('button', name='Continue').click()
    n=pg.locator('.field-error').count(); ok('3: all required errors shown', n==4, f'{n} errors')
    pg.get_by_label('First name').fill('Rosa'); pg.get_by_label('Last name').fill('Diaz')
    pg.get_by_role('button', name='Choose date from calendar').click()
    pg.get_by_label('Year').fill('1990'); pg.get_by_role('button', name='March 15, 1990').count()
    pg.get_by_role('button', name='Next month').click(); pg.get_by_role('button', name='Next month').click()
    pg.get_by_role('button', name='March 15, 1990').click()
    ok('calendar sets date of birth', pg.get_by_label('Date of birth').input_value()=='03/15/1990', pg.get_by_label('Date of birth').input_value())
    pg.get_by_role('button', name=re.compile('Country code')).click()
    cc=pg.get_by_placeholder('Search country or code'); cc.fill('52')
    ok('country search by dial code', 'Mexico' in pg.get_by_role('listbox').inner_text()); cc.press('Enter')
    ok('country changed to MX +52', 'MX' in pg.locator('.country-btn').inner_text())
    pg.get_by_role('button', name=re.compile('Country code')).click(); pg.get_by_placeholder('Search country or code').fill('United St'); pg.get_by_placeholder('Search country or code').press('Enter')
    pg.get_by_label('Mobile number').fill('3055550123')
    ok('US phone formats as typed', pg.get_by_label('Mobile number').input_value()=='(305) 555-0123')
    noscroll(pg,'3 about'); pg.screenshot(path=SHOT+'app-3.png', full_page=True)
    pg.get_by_role('button', name='Continue').click(); pg.wait_for_selector('text=get paid')
    pg.get_by_role('radio', name=re.compile('Wages or benefits')).click()
    ok('4: wages shows suitability warning', 'not wages or benefits' in pg.content())
    pg.get_by_role('button', name='Continue').click()
    ok('4: wages blocks continue', 'Fundo is for money you earn' in pg.content())
    pg.get_by_role('radio', name=re.compile('Payouts from apps')).click()
    pg.get_by_label(re.compile('use my own name')).check()
    ok('own name fills business name', pg.get_by_role('textbox', name='Business name').input_value()=='Rosa Diaz')
    pg.get_by_role('radio', name='Half or less').click()
    ok('minority owner: share module replaces Continue', pg.get_by_role('button', name='Send quote').is_visible() and pg.get_by_role('button', name='Continue').count()==0)
    pg.get_by_label('Their email').fill('name@example.com'); pg.get_by_role('button', name='Send quote').click()
    ok('share rejects your own email', 'not yours' in pg.content())
    pg.get_by_label('Their email').fill('owner@example.com'); pg.get_by_role('button', name='Send quote').click()
    pg.wait_for_selector('text=Quote sent.'); ok('quote shared with owner', True)
    noscroll(pg,'4 business'); pg.screenshot(path=SHOT+'app-4-share.png', full_page=True)
    pg.get_by_role('radio', name='More than half').click(); pg.get_by_role('button', name='Continue').click(); pg.wait_for_selector('text=home address')
    pg.get_by_role('button', name='Continue').click(); ok('5a: address errors', pg.locator('.field-error').count()==3)
    pg.get_by_label('Street address').fill('2150 Coral Way'); pg.get_by_label('City').fill('Miami'); pg.get_by_label('ZIP code').fill('33145')
    ok('state locked from answers', 'Florida' in pg.locator('.locked').inner_text())
    noscroll(pg,'5a home')
    # Finish later → resume
    pg.get_by_role('button', name='Finish later').click()
    ok('finish-later dialog names the step', 'Step 5 of 7' in pg.get_by_role('dialog').inner_text())
    pg.get_by_role('button', name='Close and finish later').click()
    ok('returning customer sees resume card', pg.get_by_text('Welcome back').is_visible())
    pg.screenshot(path=SHOT+'app-resume.png', full_page=True)
    pg.get_by_role('button', name='Continue where you left off').click()
    ok('resume lands on the saved step with answers', 'home address' in pg.locator('h1').inner_text() and pg.get_by_label('City').input_value()=='Miami')
    pg.get_by_role('button', name='Continue').click(); pg.wait_for_selector('text=your SSN')
    ssn=pg.get_by_label('Social Security number'); ssn.fill('666123456'); pg.get_by_role('button', name='Continue to connect your bank').click()
    ok('SSN invalid area rejected', 'isn’t a valid SSN' in pg.content())
    ok('SSN masked by default', ssn.get_attribute('type')=='password')
    ssn.fill('123456789'); ok('SSN formats', ssn.input_value()=='123-45-6789')
    stored=pg.evaluate("localStorage.getItem('fundo.apply.draft.v1')"); ok('SSN never stored in the browser', '123-45' not in (stored or ''))
    noscroll(pg,'5b ssn'); pg.screenshot(path=SHOT+'app-5b.png', full_page=True)
    pg.get_by_role('button', name='Continue to connect your bank').click(); pg.wait_for_selector('text=connect your bank')
    ok('reaches bank hand-off', True)
    ok('no console/page errors', not errs, '; '.join(errs)[:200])
    # network failure + slow
    for mode in ('fail','slow'):
        pg2=ctx.new_page(); pg2.goto(B+'?net='+mode); pg2.evaluate("localStorage.clear()"); pg2.reload()
        pg2.get_by_role('button', name='Check if I can apply').click()
        c=pg2.get_by_role('combobox'); c.fill('Texas'); c.press('Enter')
        pg2.get_by_role('radio', name='3+ years').click(); pg2.get_by_role('radio', name='Over $6,000').click(); pg2.get_by_role('button', name='Continue').click()
        pg2.get_by_label(re.compile('Where should we send')).fill('name@example.com'); pg2.get_by_role('button', name='Save my quote and continue').click()
        if mode=='fail':
            pg2.wait_for_selector('text=We couldn’t reach Fundo.')
            ok('network error banner + retry, answers kept', pg2.get_by_role('button', name='Try again').is_visible() and pg2.get_by_label(re.compile('Where should')).input_value()=='name@example.com')
            pg2.screenshot(path=SHOT+'app-error.png', full_page=True)
        else:
            ok('saving state shows', pg2.get_by_role('button', name='Saving…').is_visible())
            pg2.wait_for_selector('text=slow connection', timeout=8000)
            ok('slow-connection reassurance after 5 s', True); pg2.screenshot(path=SHOT+'app-slow.png', full_page=True)
        pg2.close()
    # dark mode
    dk=br.new_context(viewport={'width':360,'height':780}, color_scheme='dark').new_page()
    dk.goto(B); dk.wait_for_selector('#step-title')
    bg=dk.evaluate("getComputedStyle(document.body).backgroundColor"); ok('dark mode follows the phone', bg=='rgb(16, 20, 22)', bg)
    dk.screenshot(path=SHOT+'app-A-dark.png', full_page=True)
    # 320 px
    sm=br.new_context(viewport={'width':320,'height':700}).new_page(); sm.goto(B); sm.wait_for_selector('#step-title')
    sw=sm.evaluate('document.documentElement.scrollWidth'); ok('no horizontal scroll @320', sw<=320, f'{sw}')
    br.close()
for r in results: print(*r)
print(sum(r[0]=='PASS' for r in results),'pass,',sum(r[0]=='FAIL' for r in results),'fail')
